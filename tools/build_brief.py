#!/usr/bin/env python3
"""Build the Markdown current-state record. The archived HTML is not updated."""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]
source = ROOT / 'docs/project-state.json'
data = json.loads(source.read_text(encoding='utf-8'))

lines = ['<!-- Generated by tools/build_brief.py; edit project-state.json instead. -->',
         '# Project Nucleon — current state', '', f'Snapshot: {data["snapshot"]}', '',
         data['authority'], '', 'English is followed by Chinese in each section. Status labels identify instructions, proposals and open questions; they do not establish team consensus.', '']
for section in data['sections']:
    lines += [f'## {section["nav"]["en"]} / {section["nav"]["zh"]}', '']
    for lang in ['en', 'zh']:
        lines += [f'### {section["title"][lang]}', '', section['lead'][lang], '']
        for card in section.get('cards', []):
            ref = f' Source: {card["source"]}.' if 'source' in card else ''
            lines += [f'- **[{card["status"]}] {card["title"][lang]}:** {card["body"][lang]}{ref}']
        if section.get('cards'): lines += ['']
        if 'table' in section:
            table = section['table']
            lines += ['| ' + ' | '.join(h[lang] for h in table['headers']) + ' |',
                      '| ' + ' | '.join('---' for _ in table['headers']) + ' |']
            for row in table['rows']:
                lines += ['| ' + ' | '.join(cell[lang].replace('|', '\\|') for cell in row) + ' |']
            lines += ['']
        for bullet in section.get('bullets', []): lines += ['- ' + bullet[lang]]
        lines += ['']
lines += ['## Source register', '']
for item in data['sources']:
    title = f'[{item["name"]}]({item["url"]})' if item.get('url') else item['name']
    lines += [f'- **{item["id"]} — {title}** ({item["kind"]}). {item["detail"]}']
lines += ['', '## Knowledge-workflow research', '']
for item in data['research']:
    lines += [f'- [{item["name"]}]({item["url"]}): {item["finding"]}']
(ROOT / 'docs/PROJECT-STATE.md').write_text('\n'.join(lines) + '\n', encoding='utf-8')
print(f'Built docs/PROJECT-STATE.md from {source.name}; archived HTML left unchanged.')
